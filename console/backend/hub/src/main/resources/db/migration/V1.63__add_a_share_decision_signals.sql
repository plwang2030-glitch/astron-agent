-- A-share: the agents' trading opinions saved as evaluable signals, plus their after-the-fact
-- outcomes. This lets the analysis side be measured by evidence the same way the quant strategy is.
CREATE TABLE IF NOT EXISTS `ashare_decision_signal` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `uid` varchar(64) NOT NULL,
  `code` varchar(8) NOT NULL,
  `name` varchar(64) DEFAULT NULL,
  `action` varchar(16) NOT NULL COMMENT 'BUY / ADD / HOLD / WATCH / REDUCE / SELL / AVOID / ALERT',
  `horizon` varchar(8) NOT NULL COMMENT 'Evaluation window in trading days: 1d / 3d / 5d / 10d',
  `confidence` decimal(4,2) DEFAULT NULL COMMENT '0.00-1.00',
  `entry_low` decimal(12,3) DEFAULT NULL,
  `entry_high` decimal(12,3) DEFAULT NULL,
  `stop_loss` decimal(12,3) DEFAULT NULL,
  `target_price` decimal(12,3) DEFAULT NULL,
  `reason` varchar(1000) DEFAULT NULL COMMENT 'Why, including the evidence referenced',
  `risk` varchar(500) DEFAULT NULL,
  `watch` varchar(500) DEFAULT NULL COMMENT 'What to watch / what would invalidate it',
  `source` varchar(16) NOT NULL DEFAULT 'AGENT' COMMENT 'AGENT / REVIEW',
  `bot_id` int DEFAULT NULL COMMENT 'Agent that recorded it',
  `report_id` bigint DEFAULT NULL COMMENT 'Review report it came from',
  `market_phase` varchar(16) DEFAULT NULL COMMENT 'PRE_OPEN / INTRADAY / AFTER_CLOSE / CLOSED',
  `data_quality` varchar(8) DEFAULT NULL COMMENT 'GOOD / FAIR / POOR when recorded',
  `plan_quality` varchar(8) DEFAULT NULL COMMENT 'COMPLETE / PARTIAL / MINIMAL',
  `anchor_date` date NOT NULL COMMENT 'Trading day the evaluation starts from',
  `anchor_price` decimal(12,3) DEFAULT NULL COMMENT 'Adjusted close of anchor_date',
  `status` varchar(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING / HIT / MISS / UNABLE / SUPERSEDED',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_ashare_signal_uid_status` (`uid`,`status`,`anchor_date`),
  KEY `idx_ashare_signal_uid_code` (`uid`,`code`,`anchor_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Agent trading opinions as evaluable signals';

CREATE TABLE IF NOT EXISTS `ashare_signal_outcome` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `signal_id` bigint NOT NULL,
  `uid` varchar(64) NOT NULL,
  `code` varchar(8) NOT NULL,
  `horizon` varchar(8) NOT NULL,
  `anchor_date` date NOT NULL,
  `anchor_price` decimal(12,3) NOT NULL,
  `end_date` date DEFAULT NULL,
  `end_price` decimal(12,3) DEFAULT NULL,
  `min_low` decimal(12,3) DEFAULT NULL COMMENT 'Lowest low within the window',
  `max_high` decimal(12,3) DEFAULT NULL,
  `return_pct` decimal(10,3) DEFAULT NULL COMMENT 'end vs anchor, adjusted prices',
  `max_adverse_pct` decimal(10,3) DEFAULT NULL COMMENT 'Worst move against the opinion',
  `result` varchar(16) NOT NULL COMMENT 'HIT / MISS / UNABLE',
  `detail` varchar(500) DEFAULT NULL COMMENT 'Why, or why it could not be evaluated',
  `action` varchar(16) NOT NULL COMMENT 'Frozen at evaluation, for stable statistics',
  `market_phase` varchar(16) DEFAULT NULL,
  `source` varchar(16) NOT NULL,
  `data_quality` varchar(8) DEFAULT NULL,
  `plan_quality` varchar(8) DEFAULT NULL,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_ashare_outcome_signal` (`signal_id`),
  KEY `idx_ashare_outcome_uid` (`uid`,`result`,`anchor_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT 'Post-hoc evaluation of decision signals';
